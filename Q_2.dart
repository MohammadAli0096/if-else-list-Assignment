// Q.2: Take two variables and store age then using if/else condition to determine oldest and youngest among them.

void main() {
  int ali = 30;
  int ahmed = 25;
  print("Ali's age: $ali");
  print("Ahmed's age: $ahmed");
  if (ali > ahmed) {
    print("Ali is older than Ahmed");
  } else {
    print("Ahmed is older than Ali");
  }
}
